package auth

import (
	"context"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strings"
	"time"
)

// OAuth endpoints, identical to schwab-py.
const (
	AuthorizeEndpoint = "https://api.schwabapi.com/v1/oauth/authorize"
	TokenEndpoint     = "https://api.schwabapi.com/v1/oauth/token"
)

// OAuthClient performs the authorization-code flow against Schwab's OAuth
// endpoints. The token endpoint base URL can be overridden for tests.
type OAuthClient struct {
	APIKey      string
	AppSecret   string
	TokenURL    string // defaults to TokenEndpoint
	HTTPClient  *http.Client
	StateLength int

	// WaitBeforeRequest, when set, runs before every token-endpoint
	// request. The CLI uses it to pace token exchanges and refreshes
	// through the same shared rate limiter as REST calls, so the
	// 120-requests-per-minute budget covers them too. Nil means no
	// pacing (the zero value used by library-style callers and tests).
	WaitBeforeRequest func(ctx context.Context) error
}

func (c *OAuthClient) httpClient() *http.Client {
	if c.HTTPClient != nil {
		return c.HTTPClient
	}
	return http.DefaultClient
}

func (c *OAuthClient) tokenURL() string {
	if c.TokenURL != "" {
		return c.TokenURL
	}
	return TokenEndpoint
}

// NewState returns a random OAuth state string, as generated by authlib in
// schwab-py's get_auth_context.
func NewState() (string, error) {
	b := make([]byte, 24)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(b), nil
}

// AuthorizationURL builds the authorize URL for the manual/login flow,
// mirroring schwab-py's get_auth_context / OAuth2Client.create_authorization_url.
func (c *OAuthClient) AuthorizationURL(callbackURL, state string) string {
	q := url.Values{}
	q.Set("client_id", c.APIKey)
	q.Set("redirect_uri", callbackURL)
	q.Set("response_type", "code")
	if state != "" {
		q.Set("state", state)
	}
	return AuthorizeEndpoint + "?" + q.Encode()
}

// ParseCallbackCode extracts the authorization code from the URL the user's
// browser was redirected to after authorization (schwab-py's fetch_token with
// authorization_response). It validates the returned state when expectedState
// is non-empty.
func ParseCallbackCode(callbackURL, expectedState string) (string, error) {
	u, err := url.Parse(strings.TrimSpace(callbackURL))
	if err != nil {
		return "", fmt.Errorf("could not parse redirect URL: %w", err)
	}
	q := u.Query()
	if e := q.Get("error"); e != "" {
		return "", fmt.Errorf("authorization failed: %s (%s)", e, q.Get("error_description"))
	}
	if expectedState != "" {
		if got := q.Get("state"); got != expectedState {
			return "", fmt.Errorf("state mismatch: expected %q, got %q", expectedState, got)
		}
	}
	code := q.Get("code")
	if code == "" {
		return "", fmt.Errorf("redirect URL contains no code parameter: %s", callbackURL)
	}
	return code, nil
}

type tokenResponse struct {
	Token
}

// postToken performs a form POST against the token endpoint with HTTP Basic
// authentication (app key as username, app secret as password), exactly as
// authlib does for schwab-py.
func (c *OAuthClient) postToken(ctx context.Context, form url.Values) (*Token, error) {
	if c.WaitBeforeRequest != nil {
		if err := c.WaitBeforeRequest(ctx); err != nil {
			return nil, err
		}
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, c.tokenURL(),
		strings.NewReader(form.Encode()))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/x-www-form-urlencoded")
	req.Header.Set("Accept", "application/json")
	req.SetBasicAuth(c.APIKey, c.AppSecret)

	resp, err := c.httpClient().Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return nil, fmt.Errorf("token endpoint returned %s: %s",
			resp.Status, strings.TrimSpace(string(body)))
	}
	var tok Token
	if err := json.Unmarshal(body, &tok); err != nil {
		return nil, fmt.Errorf("parsing token response: %w", err)
	}
	// authlib records expires_at alongside expires_in; do the same so the
	// token file carries an absolute expiry.
	if tok.ExpiresAt == 0 && tok.ExpiresIn > 0 {
		tok.ExpiresAt = time.Now().Unix() + tok.ExpiresIn
	}
	return &tok, nil
}

// ExchangeCode trades an authorization code for a token, mirroring
// schwab-py's client_from_received_url / OAuth2Client.fetch_token.
func (c *OAuthClient) ExchangeCode(ctx context.Context, callbackURL, code string) (*Token, error) {
	form := url.Values{}
	form.Set("grant_type", "authorization_code")
	form.Set("code", code)
	form.Set("redirect_uri", callbackURL)
	return c.postToken(ctx, form)
}

// Refresh performs a refresh-token grant. The returned token's response
// carries a new refresh token, but — as in schwab-py — the grant's creation
// timestamp (and therefore its 7-day deadline) is unchanged.
func (c *OAuthClient) Refresh(ctx context.Context, refreshToken string) (*Token, error) {
	form := url.Values{}
	form.Set("grant_type", "refresh_token")
	form.Set("refresh_token", refreshToken)
	return c.postToken(ctx, form)
}

// Manager owns a token file and an OAuth client, and hands out fresh access
// tokens, refreshing and persisting them the way schwab-py's session does.
type Manager struct {
	Path  string
	OAuth *OAuthClient
	Now   func() time.Time // injectable clock for tests
}

func (m *Manager) now() time.Time {
	if m.Now != nil {
		return m.Now()
	}
	return time.Now()
}

// Load reads the current token file.
func (m *Manager) Load() (*TokenFile, error) {
	return LoadTokenFile(m.Path)
}

// FreshToken returns a token whose access token is valid, refreshing and
// saving it first if necessary. The creation timestamp is preserved across
// refreshes, mirroring schwab-py's TokenMetadata.
func (m *Manager) FreshToken(ctx context.Context) (*TokenFile, error) {
	tf, err := m.Load()
	if err != nil {
		return nil, err
	}
	now := m.now()
	if !tf.AccessTokenExpired(now) {
		return tf, nil
	}
	if tf.RefreshTokenExpired(now) {
		return nil, ErrRefreshTokenExpired
	}
	newTok, err := m.OAuth.Refresh(ctx, tf.Token.RefreshToken)
	if err != nil {
		return nil, fmt.Errorf("refreshing token: %w", err)
	}
	// Schwab may omit a new refresh token; retain the existing one if so.
	if newTok.RefreshToken == "" {
		newTok.RefreshToken = tf.Token.RefreshToken
	}
	tf.Token = *newTok
	if err := tf.Save(m.Path); err != nil {
		return nil, fmt.Errorf("saving refreshed token: %w", err)
	}
	return tf, nil
}

// AccessToken returns a valid access-token string for use in an
// Authorization header.
func (m *Manager) AccessToken(ctx context.Context) (string, error) {
	tf, err := m.FreshToken(ctx)
	if err != nil {
		return "", err
	}
	return tf.Token.AccessToken, nil
}
